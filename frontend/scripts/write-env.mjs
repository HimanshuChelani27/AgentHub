// Writes public/env.js from AGENTHUB_API_URL so the same build can point at any backend.
import { writeFileSync } from "node:fs";

const apiUrl = (process.env.AGENTHUB_API_URL || "http://localhost:8000").replace(/\/$/, "");
writeFileSync(
  new URL("../public/env.js", import.meta.url),
  `// Generated by scripts/write-env.mjs\nwindow.__AGENTHUB__ = { apiUrl: ${JSON.stringify(apiUrl)} };\n`,
);
console.log(`env.js -> ${apiUrl}`);
